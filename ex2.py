class MATH:
    def add(self,a,b):
        print('the addition of:',a+b)
    def sub(self,a,b):
        print('the Subtraction of:',a-b)
    def mul(self,a,b):
        print('the multilication of:',a*b)
    def div(self,a,b):
        print('the division of:',a/b)

obj=MATH()
obj.add(10,20)
